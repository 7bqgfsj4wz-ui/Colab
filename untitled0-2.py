import time
import matplotlib.pyplot as plt

def doppelte_summe(n):
    s = 0
    for i in range(1, n + 1):
        for j in range(1, i + 1):
            s += j
    return s

# Verschiedene Werte für n
ns = [100, 200, 400, 600, 800, 1000]
zeiten = []

for n in ns:
    start = time.time()
    doppelte_summe(n)
    ende = time.time()
    zeiten.append(ende - start)

# Darstellung
plt.plot(ns, zeiten, marker="o")
plt.xlabel("n")
plt.ylabel("Laufzeit in Sekunden")
plt.title("Laufzeit der doppelten Summe")
plt.grid(True)
plt.show()

