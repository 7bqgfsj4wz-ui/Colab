import time
import matplotlib.pyplot as plt

def summe_naiv(n):
    s = 0
    for i in range(1, n + 1):
        s += i
    return s

ns = [10**k for k in range(1, 7)]
zeiten = []

for n in ns:
    start = time.time()
    summe_naiv(n)
    ende = time.time()
    zeiten.append(ende - start)

plt.plot(ns, zeiten, marker="o")
plt.xlabel("n")
plt.ylabel("Laufzeit (Sekunden)")
plt.title("Laufzeit der naiven Summenfunktion")
plt.xscale("log")
plt.yscale("log")
plt.show()

