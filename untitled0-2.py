def collatz(n):
    folge = [n]

    while n != 1:
        if n % 2 == 0:      # n ist gerade
            n = n // 2
        else:               # n ist ungerade
            n = 3 * n + 1
        folge.append(n)

    return folge

startwerte = [6, 11, 19, 27]

for n in startwerte:
    f = collatz(n)
    print(f"Startwert {n}:")
    print(f"  Folge: {f}")
    print(f"  Länge der Folge: {len(f)}\n")